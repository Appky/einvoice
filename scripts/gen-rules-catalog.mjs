#!/usr/bin/env node
/**
 * Extract every EN 16931 rule id + official text from the official Schematron
 * artefacts into a generated TypeScript catalog. Fix guidance is layered on
 * top from src/rules-fixes.ts (hand-written, curated).
 *
 * Usage: node scripts/gen-rules-catalog.mjs <EN16931-model.sch> <EN16931-UBL-codes.sch>
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const paths = process.argv.slice(2);
if (paths.length < 2) {
  console.error("usage: gen-rules-catalog.mjs <model.sch> <codes.sch>");
  process.exit(1);
}

const rules = new Map();
for (const path of paths) {
  const src = readFileSync(path, "utf8");
  for (const m of src.matchAll(/<assert[^>]*?flag="(\w+)"[^>]*?id="((?:BR|PEPPOL-EN16931)[A-Za-z0-9-]*)"[^>]*>\s*(?:\[[^\]]+\]\s*-?\s*)?([\s\S]*?)<\/assert>/g)) {
    const [, flag, id, rawText] = m;
    const text = rawText.replace(/\s+/g, " ").trim();
    if (!rules.has(id)) rules.set(id, { severity: flag === "warning" ? "warning" : "fatal", text });
  }
  // Attribute order variant: id before flag.
  for (const m of src.matchAll(/<assert[^>]*?id="((?:BR|PEPPOL-EN16931)[A-Za-z0-9-]*)"[^>]*?flag="(\w+)"[^>]*>\s*(?:\[[^\]]+\]\s*-?\s*)?([\s\S]*?)<\/assert>/g)) {
    const [, id, flag, rawText] = m;
    const text = rawText.replace(/\s+/g, " ").trim();
    if (!rules.has(id)) rules.set(id, { severity: flag === "warning" ? "warning" : "fatal", text });
  }
}

const here = dirname(fileURLToPath(import.meta.url));
const outPath = join(here, "..", "packages", "core", "src", "gen", "rules-catalog.ts");
mkdirSync(dirname(outPath), { recursive: true });

const sorted = [...rules.entries()].sort(([a], [b]) => a.localeCompare(b, "en", { numeric: true }));
let out = `// GENERATED by scripts/gen-rules-catalog.mjs from the official EN 16931
// Schematron artefacts (ConnectingEurope/eInvoicing-EN16931). Do not edit.
/* eslint-disable */
export interface RuleInfo {
  severity: "fatal" | "warning";
  /** Official rule text as published in the validation artefacts. */
  text: string;
}
export const RULE_TEXTS: Record<string, RuleInfo> = {
`;
for (const [id, r] of sorted) {
  out += `  ${JSON.stringify(id)}: { severity: ${JSON.stringify(r.severity)}, text: ${JSON.stringify(r.text)} },\n`;
}
out += `};\n`;
writeFileSync(outPath, out);
console.log(`wrote ${outPath} with ${rules.size} rules`);
