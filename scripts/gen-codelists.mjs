#!/usr/bin/env node
/**
 * Extract code lists from the official EN 16931 UBL codelist Schematron
 * (ConnectingEurope/eInvoicing-EN16931, EUPL 1.2) into generated TypeScript.
 *
 * The code values themselves are standardized facts (ISO 4217, ISO 3166,
 * UNTDID/UNCL, ISO 6523 ICD, EAS, VATEX); we extract rather than hand-type
 * them so they can be regenerated mechanically when the artefacts update.
 *
 * Usage: node scripts/gen-codelists.mjs <path-to-EN16931-UBL-codes.sch>
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const schPath = process.argv[2];
if (!schPath) {
  console.error("usage: gen-codelists.mjs <EN16931-UBL-codes.sch>");
  process.exit(1);
}
const src = readFileSync(schPath, "utf8");

// Match each <assert ... test="..." id="BR-CL-xx" ...> block (attribute order varies).
const modelPath = process.argv[3];
const modelSrc = modelPath ? readFileSync(modelPath, "utf8") : "";

const asserts = [
  ...src.matchAll(/<assert\b([\s\S]*?)>/g),
  ...modelSrc.matchAll(/<param\b([\s\S]*?)\/>/g),
];
const byRule = new Map();
for (const m of asserts) {
  const attrs = m[1];
  const idMatch = /(?:id|name)="(BR-CL-\d+|BR-CO-09)"/.exec(attrs);
  if (!idMatch) continue;
  const id = idMatch[1];
  let lists = [...attrs.matchAll(/contains\(\s*'((?:[^']|'')*)'/g)].map((x) => x[1].trim().split(/\s+/));
  if (lists.length === 0) {
    // Alternate style: a chain of `X = 'value' or X = 'value'` comparisons.
    const eqValues = [...attrs.matchAll(/=\s*'([^']+)'/g)].map((x) => x[1]);
    if (eqValues.length > 0) lists = [eqValues];
  }
  if (lists.length === 0) continue;
  const existing = byRule.get(id) ?? [];
  byRule.set(id, existing.concat(lists));
}

const here = dirname(fileURLToPath(import.meta.url));
const outPath = join(here, "..", "packages", "core", "src", "gen", "codelists.ts");
mkdirSync(dirname(outPath), { recursive: true });

let out = `// GENERATED by scripts/gen-codelists.mjs from the official EN 16931 UBL
// codelist Schematron (ConnectingEurope/eInvoicing-EN16931). Do not edit by
// hand; regenerate when the validation artefacts are updated.
/* eslint-disable */
`;
const seen = [];
for (const [id, lists] of [...byRule.entries()].sort()) {
  const name = "CODES_" + id.replaceAll("-", "_");
  seen.push([id, name, lists.length]);
  if (lists.length === 1) {
    out += `export const ${name}: ReadonlySet<string> = new Set(${JSON.stringify(lists[0])});\n`;
  } else {
    out += `export const ${name}: ReadonlyArray<ReadonlySet<string>> = [\n`;
    for (const l of lists) out += `  new Set(${JSON.stringify(l)}),\n`;
    out += `];\n`;
  }
}
writeFileSync(outPath, out);
console.log("wrote", outPath);
for (const [id, name, n] of seen) console.log(`  ${id} -> ${name} (${n} list(s))`);
